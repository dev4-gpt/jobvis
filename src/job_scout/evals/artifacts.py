"""Deterministic checks for the files a user actually downloads.

Model-level backtests are necessary but insufficient: a valid ``TailoringPack``
can still render without PDF annotations, lose links, produce sparse pages, or
compile a weak cover letter.  This module audits the rendered artifacts without
calling a model or contacting a job board.
"""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

from pypdf import PdfReader

from job_scout.cover_letter_quality import evaluate_cover_letter
from job_scout.tools.cv_reader import CVReadError, extract_cv_document


@dataclass(frozen=True)
class ArtifactIssue:
    code: str
    severity: str
    message: str


@dataclass(frozen=True)
class ArtifactManifest:
    """Authoritative manifest for the files a user may download."""

    status: str
    cv_pdf: str | None
    cv_tex: str | None
    cover_letter_pdf: str | None
    cover_letter_tex: str | None
    cv_pages: int
    cv_words: int
    cover_letter_words: int
    source_links: int
    generated_links: int
    annotation_count: int
    issue_codes: tuple[str, ...] = ()
    selected_job_id: str = ""
    profile_version: str = ""
    generation_id: str = ""
    backtest_score: float | None = None

    @property
    def pdfs_ready(self) -> bool:
        return self.status == "ready" and bool(self.cv_pdf and self.cover_letter_pdf)

    def as_dict(self) -> dict:
        return {
            "status": self.status,
            "cv_pdf": self.cv_pdf,
            "cv_tex": self.cv_tex,
            "cover_letter_pdf": self.cover_letter_pdf,
            "cover_letter_tex": self.cover_letter_tex,
            "pdfs_ready": self.pdfs_ready,
            "cv_pages": self.cv_pages,
            "cv_words": self.cv_words,
            "cover_letter_words": self.cover_letter_words,
            "source_links": self.source_links,
            "generated_links": self.generated_links,
            "annotation_count": self.annotation_count,
            "issue_codes": list(self.issue_codes),
            "selected_job_id": self.selected_job_id,
            "profile_version": self.profile_version,
            "generation_id": self.generation_id,
            "backtest_score": self.backtest_score,
        }


@dataclass(frozen=True)
class ArtifactReport:
    passed: bool
    original_cv: str
    tailored_cv: str
    cover_letter: str
    cv_pages: int
    cv_words: int
    cover_letter_words: int
    source_links: int
    generated_links: int
    annotation_count: int
    missing_links: tuple[str, ...]
    issues: tuple[ArtifactIssue, ...]
    hashes: dict[str, str]

    def as_dict(self) -> dict:
        return {
            "passed": self.passed,
            "original_cv": self.original_cv,
            "tailored_cv": self.tailored_cv,
            "cover_letter": self.cover_letter,
            "cv_pages": self.cv_pages,
            "cv_words": self.cv_words,
            "cover_letter_words": self.cover_letter_words,
            "source_links": self.source_links,
            "generated_links": self.generated_links,
            "annotation_count": self.annotation_count,
            "missing_links": list(self.missing_links),
            "issues": [issue.__dict__ for issue in self.issues],
            "hashes": self.hashes,
        }


_CORRUPTION_PATTERNS = (
    ("split_acronym", re.compile(r"\b(?:A\s+WS|F\s+AISS|R\s+AG|LL\s+M|AP\s+I)\b", re.I)),
    ("split_layout_word", re.compile(r"\b(?:V\s+eloce|A\s+I|M\s+L|Open\s+AI|Lang\s+Chain)\b", re.I)),
    (
        "malformed_project_title",
        re.compile(r"\b(?:research assistantship\s+and\s+operating system|operating system\s*\(cursor)\b", re.I),
    ),
    (
        "internal_marker",
        re.compile(r"\b(?:verified evidence|provider fallback used|generated by|researchingos workflow)\b", re.I),
    ),
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _read_pdf(path: Path) -> tuple[str, int, int]:
    reader = PdfReader(str(path))
    pages = [page.extract_text() or "" for page in reader.pages]
    return "\n".join(pages).strip(), len(reader.pages), len(pages)


def _add_corruption_issues(text: str, issues: list[ArtifactIssue]) -> None:
    for code, pattern in _CORRUPTION_PATTERNS:
        if pattern.search(text):
            issues.append(
                ArtifactIssue(code, "blocker", f"Rendered artifact contains a known corruption/internal marker: {code}")
            )


def _qpdf_check(path: Path, issues: list[ArtifactIssue], label: str) -> None:
    """Run an optional structural PDF check when qpdf is installed locally."""
    binary = shutil.which("qpdf")
    if binary is None or not path.is_file():
        return
    try:
        result = subprocess.run(
            [binary, "--json", str(path), "-"],
            capture_output=True,
            text=True,
            timeout=15,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        issues.append(ArtifactIssue("qpdf_check_failed", "warning", f"{label} qpdf check did not complete: {exc}"))
        return
    if result.returncode != 0:
        issues.append(ArtifactIssue("qpdf_invalid", "blocker", f"{label} failed qpdf structural validation."))


def audit_rendered_pack(
    original_cv: str | Path,
    tailored_cv: str | Path,
    *,
    cover_letter_pdf: str | Path | None = None,
    cover_letter_text: str | None = None,
    job_description: str = "",
    cv_tex: str | Path | None = None,
    cover_letter_tex: str | Path | None = None,
) -> ArtifactReport:
    """Audit generated CV/letter files and require original links to survive."""
    original = Path(original_cv)
    tailored = Path(tailored_cv)
    letter = Path(cover_letter_pdf) if cover_letter_pdf else None
    issues: list[ArtifactIssue] = []
    hashes: dict[str, str] = {}

    try:
        source_text, source_links = extract_cv_document(original)
        hashes["original_cv"] = _sha256(original)
    except (CVReadError, OSError, ValueError) as exc:
        issues.append(ArtifactIssue("original_cv_unreadable", "blocker", str(exc)))
        source_text, source_links = "", []

    return _audit_generated_files(
        source_text=source_text,
        source_links=source_links,
        tailored=tailored,
        letter=letter,
        cover_letter_text=cover_letter_text,
        job_description=job_description,
        cv_tex=cv_tex,
        cover_letter_tex=cover_letter_tex,
        original_cv=str(original),
        hashes=hashes,
        issues=issues,
    )


def audit_generated_pack(
    source_text: str,
    source_links: Iterable[object],
    tailored_cv: str | Path,
    *,
    cover_letter_pdf: str | Path | None = None,
    cover_letter_text: str | None = None,
    job_description: str = "",
    cv_tex: str | Path | None = None,
    cover_letter_tex: str | Path | None = None,
) -> ArtifactReport:
    """Audit a live checkpoint pack without reopening the private source PDF.

    The wizard already has the redacted CV text and typed PDF links in the
    checkpoint.  This entry point lets the API apply the exact same checks to
    rendered files without putting the user's local resume path into state or
    traces.
    """
    return _audit_generated_files(
        source_text=source_text,
        source_links=source_links,
        tailored=Path(tailored_cv),
        letter=Path(cover_letter_pdf) if cover_letter_pdf else None,
        cover_letter_text=cover_letter_text,
        job_description=job_description,
        cv_tex=cv_tex,
        cover_letter_tex=cover_letter_tex,
        original_cv="checkpoint source resume",
        hashes={},
        issues=[],
    )


def _audit_generated_files(
    *,
    source_text: str,
    source_links: Iterable[object],
    tailored: Path,
    letter: Path | None,
    cover_letter_text: str | None,
    job_description: str,
    cv_tex: str | Path | None,
    cover_letter_tex: str | Path | None,
    original_cv: str,
    hashes: dict[str, str],
    issues: list[ArtifactIssue],
) -> ArtifactReport:
    """Shared implementation for disk-source and checkpoint-source audits."""
    try:
        tailored_text, cv_pages, _ = _read_pdf(tailored)
        hashes["tailored_cv"] = _sha256(tailored)
    except (OSError, ValueError) as exc:
        issues.append(ArtifactIssue("tailored_cv_unreadable", "blocker", f"Could not read tailored CV: {exc}"))
        tailored_text, cv_pages = "", 0
    try:
        _, tailored_links = extract_cv_document(tailored)
    except (CVReadError, OSError, ValueError):
        tailored_links = []

    if cv_pages < 1:
        issues.append(ArtifactIssue("tailored_cv_empty", "blocker", "Tailored CV has no readable pages."))
    _qpdf_check(tailored, issues, "Tailored CV")
    if len(tailored_text.split()) < 500:
        issues.append(ArtifactIssue("tailored_cv_sparse", "blocker", "Tailored CV has fewer than 500 extracted words."))
    if cv_pages > 2:
        issues.append(
            ArtifactIssue("tailored_cv_too_long", "warning", f"Tailored CV has {cv_pages} pages; target is one to two pages.")
        )
    if cv_pages >= 2:
        try:
            page_lengths = [len(page.extract_text() or "") for page in PdfReader(str(tailored)).pages]
        except (OSError, ValueError):
            page_lengths = []
        if len(page_lengths) >= 2 and page_lengths[-1] < max(250, page_lengths[0] // 5):
            issues.append(
                ArtifactIssue(
                    "tailored_cv_sparse_last_page", "warning", "The final CV page is unusually sparse; inspect page breaks."
                )
            )

    source_urls = {getattr(link, "url", "") for link in source_links if getattr(link, "url", "")}
    generated_urls = {link.url for link in tailored_links if link.url}
    missing_links = tuple(sorted(source_urls - generated_urls))
    if missing_links:
        issues.append(
            ArtifactIssue("missing_source_links", "blocker", f"{len(missing_links)} original clickable links are missing.")
        )
    if source_urls and not generated_urls:
        issues.append(ArtifactIssue("missing_pdf_annotations", "blocker", "Tailored CV contains no clickable PDF annotations."))
    _add_corruption_issues(tailored_text, issues)

    letter_text = cover_letter_text or ""
    letter_pages = 0
    if letter is not None:
        try:
            letter_text, letter_pages, _ = _read_pdf(letter)
            hashes["cover_letter"] = _sha256(letter)
            _qpdf_check(letter, issues, "Cover letter")
        except (OSError, ValueError) as exc:
            issues.append(ArtifactIssue("cover_letter_unreadable", "blocker", f"Could not read cover letter PDF: {exc}"))
    if not letter_text.strip():
        issues.append(ArtifactIssue("cover_letter_empty", "blocker", "No readable cover-letter text was supplied."))
    letter_quality = evaluate_cover_letter(letter_text, job_description, source_text) if letter_text.strip() else None
    letter_words = letter_quality.word_count if letter_quality else 0
    if letter_quality and not letter_quality.passed:
        for reason in letter_quality.reasons:
            issues.append(ArtifactIssue("cover_letter_quality", "blocker", reason))
    if letter is not None and letter_pages < 1:
        issues.append(ArtifactIssue("cover_letter_empty_pdf", "blocker", "Cover-letter PDF has no readable pages."))
    _add_corruption_issues(letter_text, issues)

    for label, path in (("cv_tex", cv_tex), ("cover_letter_tex", cover_letter_tex)):
        if path is not None and not Path(path).is_file():
            issues.append(ArtifactIssue(f"missing_{label}", "blocker", f"Required {label} artifact is missing."))

    return ArtifactReport(
        passed=not any(issue.severity == "blocker" for issue in issues),
        original_cv=original_cv,
        tailored_cv=str(tailored),
        cover_letter=str(letter or "text input"),
        cv_pages=cv_pages,
        cv_words=len(tailored_text.split()),
        cover_letter_words=letter_words,
        source_links=len(source_urls),
        generated_links=len(generated_urls),
        annotation_count=len(generated_urls),
        missing_links=missing_links,
        issues=tuple(issues),
        hashes=hashes,
    )
